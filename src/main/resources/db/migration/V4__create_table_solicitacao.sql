CREATE TABLE tb_solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao TEXT,
    status VARCHAR(255),
    data_criacao TIMESTAMP NOT NULL,

    solicitante_id BIGINT,
    tecnico_id BIGINT,
    categoria_id BIGINT,

    CONSTRAINT fk_solicitacao_solicitante
        FOREIGN KEY (solicitante_id) REFERENCES tb_usuarios(id),

    CONSTRAINT fk_solicitacao_tecnico
        FOREIGN KEY (tecnico_id) REFERENCES tb_usuarios(id),

    CONSTRAINT fk_solicitacao_categoria
        FOREIGN KEY (categoria_id) REFERENCES tb_categorias(id)
);